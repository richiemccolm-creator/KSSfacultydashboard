/** Titles in the tracking/reporting cycle — interim/full/parental reports, working grades, tracking entry. */
window.CAL_REPORTING_TITLE_RE = /\breports?\b|\breporting\b|working grades|tracking entry|parental report/i;
window.CAL_REPORTING_ASSESSMENT_RE = /working grades|tracking entry/i;
window.CAL_REPORTING_DEADLINE_RE = /\breports?\b/i;

window.calIsReportingRelated = function (ev) {
  var cat = String((ev && ev.category) || '').toLowerCase();
  var title = String((ev && ev.title) || '');
  var desc = String((ev && ev.description) || '');
  if (cat === 'reporting') return true;
  return window.CAL_REPORTING_TITLE_RE.test(title) || window.CAL_REPORTING_TITLE_RE.test(desc);
};

/** Reporting chip includes the whole cycle; Assessment / Deadline chips still include those same items. */
window.calEventMatchesCategory = function (ev, cat) {
  if (!cat) return true;
  var evCat = String((ev && ev.category) || 'general');
  if (evCat === cat) return true;
  var title = String((ev && ev.title) || '');
  if (cat === 'reporting' && window.calIsReportingRelated(ev)) return true;
  if (cat === 'assessment' && window.CAL_REPORTING_ASSESSMENT_RE.test(title)) return true;
  if (cat === 'deadline' && window.CAL_REPORTING_DEADLINE_RE.test(title) && /deadline|\bqa\b/i.test(title)) return true;
  if (cat === 'faculty-deadline' && window.CAL_REPORTING_DEADLINE_RE.test(title) && /deadline/i.test(title)) return true;
  return false;
};

window.calEventMatchesSearch = function (ev, q, catLabels) {
  q = String(q || '').trim().toLowerCase();
  if (!q) return true;
  var title = String((ev && ev.title) || '').toLowerCase();
  var desc = String((ev && ev.description) || '').toLowerCase();
  var date = String((ev && ev.date) || '');
  var evCat = String((ev && ev.category) || '');
  var labels = catLabels || {};
  var catLabel = String(labels[evCat] || evCat || '').toLowerCase();
  if (title.indexOf(q) !== -1 || desc.indexOf(q) !== -1 || catLabel.indexOf(q) !== -1) return true;
  if ((q === 'report' || q === 'reports' || q === 'reporting') && window.calIsReportingRelated(ev)) return true;
  if (date.indexOf(q) !== -1) return true;
  var monthNames = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];
  var parts = date.split('-');
  if (parts.length >= 2 && q.length >= 2) {
    var yr = parts[0], mo = parts[1], dy = parts[2] || '';
    if (yr.indexOf(q) !== -1 || mo.indexOf(q) !== -1 || dy.indexOf(q) !== -1) return true;
    var monthIdx = monthNames.indexOf(q);
    if (monthIdx >= 0 && parts[1] === String(monthIdx + 1).padStart(2, '0')) return true;
  }
  return false;
};

/** Align stored/shared events with current default categories (title + date). */
window.calApplyDefaultCategories = function (events, defaults) {
  defaults = defaults || window.ACADEMIC_CALENDAR_DEFAULT_EVENTS || [];
  var map = {};
  defaults.forEach(function (ev) {
    if (ev && ev.title && ev.date) map[String(ev.title) + '|' + String(ev.date).slice(0, 10)] = ev.category;
  });
  (events || []).forEach(function (e) {
    if (!e) return;
    var next = map[String(e.title || '') + '|' + String(e.date || '').slice(0, 10)];
    if (next) e.category = next;
  });
  return events;
};
